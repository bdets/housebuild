export const isVoid = (r) => r && r.status === "void";

// সব হিসাব/রিপোর্টে এটা দিয়ে ফিল্টার করুন: বাতিল রেকর্ড যোগফলে ঢুকবে না
export const liveRow = (r) => !isVoid(r);
